-- IDs are BY DEFAULT (not ALWAYS) so the deterministic seed can insert explicit
-- ids with COPY; the sequences are advanced afterwards.
CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       TEXT           NOT NULL,
    last_name        TEXT           NOT NULL,
    email            TEXT,
    phone            TEXT,
    city             TEXT           NOT NULL,
    -- Consent is independent of whether a phone/email exists on purpose:
    -- "consent but no phone" must be handled (and is present in the seed).
    sms_consent      BOOLEAN        NOT NULL,
    email_consent    BOOLEAN        NOT NULL,
    -- Derived from cart_events / orders (kept so segment queries need no joins).
    last_cart_add_at TIMESTAMPTZ,
    last_order_at    TIMESTAMPTZ,
    order_count      INT            NOT NULL DEFAULT 0,
    total_spent      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL
);

CREATE INDEX users_city_idx             ON users (city);
CREATE INDEX users_last_cart_add_at_idx ON users (last_cart_add_at);
CREATE INDEX users_last_order_at_idx    ON users (last_order_at);

CREATE TABLE cart_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_name TEXT        NOT NULL,
    added_at     TIMESTAMPTZ NOT NULL
);

CREATE INDEX cart_events_user_added_idx ON cart_events (user_id, added_at);

CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    total      NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL
);

CREATE INDEX orders_user_created_idx ON orders (user_id, created_at);

