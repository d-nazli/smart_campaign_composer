-- A campaign moves forward through these states only:
--   draft -> segment_ready -> content_ready -> approved -> sending -> completed
-- (approved/sending/completed are used by the sending phase.)
CREATE TABLE campaigns (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brief          TEXT        NOT NULL,
    status         TEXT        NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft', 'segment_ready', 'content_ready', 'approved', 'sending', 'completed')),
    -- What the LLM said about the brief: ok | needs_clarification | unsupported.
    segment_status TEXT,
    -- The validated rule as stored for display and later sending (never SQL).
    segment_rule   JSONB,
    explanation    TEXT        NOT NULL DEFAULT '',
    question       TEXT        NOT NULL DEFAULT '',
    -- Audience size at segmentation time (consent and contact data applied).
    matched        INT,
    sms_reachable  INT,
    email_reachable INT,
    both_reachable INT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The message templates the marketer reviews (and may edit) before approval.
CREATE TABLE campaign_contents (
    campaign_id   BIGINT      PRIMARY KEY REFERENCES campaigns (id) ON DELETE CASCADE,
    sms_body      TEXT        NOT NULL,
    email_subject TEXT        NOT NULL,
    email_body    TEXT        NOT NULL,
    -- llm: model output | fallback: built-in template | edited: changed by a human
    source        TEXT        NOT NULL CHECK (source IN ('llm', 'fallback', 'edited')),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Audit trail of every LLM attempt (valid or not), real or mock.
CREATE TABLE llm_generations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   BIGINT      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    kind          TEXT        NOT NULL CHECK (kind IN ('segment', 'messages')),
    attempt       INT         NOT NULL,
    mode          TEXT        NOT NULL,
    model         TEXT        NOT NULL,
    valid         BOOLEAN     NOT NULL,
    problems      JSONB       NOT NULL DEFAULT '[]',
    raw_output    TEXT        NOT NULL DEFAULT '',
    input_tokens  INT         NOT NULL DEFAULT 0,
    output_tokens INT         NOT NULL DEFAULT 0,
    latency_ms    INT         NOT NULL DEFAULT 0,
    error         TEXT        NOT NULL DEFAULT '',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX llm_generations_campaign_idx ON llm_generations (campaign_id, id);

-- One row per (campaign, recipient, channel): this table IS the send queue.
-- The unique constraint is the first line of defence against sending the same
-- message to the same person twice: enqueueing is INSERT ... ON CONFLICT DO
-- NOTHING, so approving twice or retrying a crashed approval cannot duplicate.
-- (Created now so the schema is reviewed with the rest; the sending phase uses it.)
CREATE TABLE deliveries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id         BIGINT      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    user_id             BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    channel             TEXT        NOT NULL CHECK (channel IN ('sms', 'email')),
    status              TEXT        NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'sending', 'sent', 'failed', 'skipped')),
    attempts            INT         NOT NULL DEFAULT 0,
    next_attempt_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_until        TIMESTAMPTZ,
    provider_message_id TEXT,
    last_error          TEXT        NOT NULL DEFAULT '',
    sent_at             TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT deliveries_once_per_recipient UNIQUE (campaign_id, user_id, channel)
);

-- Used by the worker's claim query (work that is due, per channel).
CREATE INDEX deliveries_claim_idx ON deliveries (channel, next_attempt_at)
    WHERE status IN ('pending', 'sending');
-- Used by dashboard aggregations.
CREATE INDEX deliveries_campaign_status_idx ON deliveries (campaign_id, channel, status);

